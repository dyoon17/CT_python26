def solution(my_string):
    answer = ''
    for c in my_string:
        if c == 'a':
            answer += ''
        elif c == 'e':
            answer += ''
        elif c == 'i':
            answer += ''
        elif c == 'o':
            answer += ''
        elif c == 'u':
            answer += ''        
        else:
            answer += c
        
    return answer